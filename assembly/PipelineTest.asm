.text
.global main
main:
    # =========================================================================
    # 0. 初始化基础寄存器
    # =========================================================================
    addi x1, x0, 0          # 清零
    addi x31, x0, 1        # 终极成功标志位：如果全通，最后给 x31 写入 99

    # =========================================================================
    # 场景一：连续 RAW 依赖轰炸（测试 MEM->EX 和 WB->EX 前向）
    # 专属输出寄存器：x10 (预期正确值：40), x11 (预期正确值：30)                             【通过！】
    # =========================================================================
test_data_forwarding:
    addi x5, x0, 10         # x5 = 10
    add  x10, x5, x5        # x10 = 10 + 10 = 20  (依赖上一条的 x5，MEM->EX 截胡)
    add  x11, x10, x5       # x11 = 20 + 10 = 30  (x10 来自 MEM->EX, x5 来自 WB->EX 擦边)

    # 极端连续挤压测试
    addi x6, x0, 5          # x6 = 5
    addi x6, x6, 5          # x6 = 10 (MEM->EX)
    addi x6, x6, 10         # x6 = 20 (MEM->EX)
    addi x6, x6, 20         # x10 = 40 (MEM->EX) -> 覆盖 x10 作为最终输出
    add  x10, x6, x0        # x10 最终锁存 40 则为成功

    # =========================================================================
    # 场景二：x0 寄存器边界前向测试
    # 专属输出寄存器：x12 (预期正确值：15)                                                 【通过！】
    # =========================================================================
test_x0_forwarding:
    addi x0, x0, 99         # 尝试写入 x0。硬件必须丢弃，x0 必须保持 0
    addi x7, x0, 15         # x7 = 15
    add  x12, x7, x0        # x12 = 15 + 0 = 15
                            # 如果你的前向模块忘记判断 (rd != 0)，
                            # 这里 x0 就会被错误地前传为 99，导致 x12 变成 114！

    # =========================================================================
    # 场景三：控制冒险与冲刷测试（JAL 与 BXX 强行清空影子指令）
    # 专属输出寄存器：x13 (预期正确值：1)、x14 (预期正确值：2)                             【通过！】
    # =========================================================================
test_control_flush:
    addi x13, x0, 1         # x13 = 1
    jal  x0, branch_flush_target # 强行跳转

    # 下面两条是 JAL 的影子指令，必须被 flush_if_id 和 flush_id_ex 斩杀化为 NOP
    addi x13, x13, 100      # 影子指令 1 (如果不被冲刷，x13 会暴增)
    addi x13, x13, 200      # 影子指令 2 (如果不被冲刷，x13 会暴增)

branch_flush_target:
    addi x14, x0, 2         # x14 = 2
    addi x8, x0, 1          # x8 = 1
    addi x9, x0, 1          # x9 = 1
    beq  x8, x9, next_test  # 1 == 1 成立，触发分支跳转

    # 下面两条是 BEQ 的影子指令，必须被洗成 NOP
    addi x14, x14, 500      # 影子指令 1 (如果不被冲刷，x14 报错)
    addi x14, x14, 600      # 影子指令 2 (如果不被冲刷，x14 报错)

    # =========================================================================
    # 场景四：控制与数据交叉冒险 (Branch 依赖上一条指令，且跳转成功)
    # 专属输出寄存器：x15 (预期正确值：3), x16 (预期正确值：55)                            【通过! 】
    # =========================================================================
next_test:
    addi x15, x0, 0         # x15 作为计数器
    addi x16, x0, 55        # x16 作为对照组基准值
    addi x17, x0, 3         # 终点线 = 3

loop_cross_hazard:
    # 构造极度危险的依赖：下一条分支指令立刻要用刚算出来的 x15
    addi x15, x15, 1        # x15 = x15 + 1
    blt  x15, x17, loop_cross_hazard
    beq  x15, x17, test_load_use

    # 下面两条是循环退出或者跳转时的影子指令，绝对不能执行！
    addi x16, x16, 1        # 影子指令 1 (如果漏风，x16 就会变成非 55 的值)
    addi x16, x16, 2        # 影子指令 2 (如果漏风，x16 就会变成非 55 的值)

    # =========================================================================
    # 场景五：Load-Use Hazard 硬件停顿（Stall）测试
    # 专属输出寄存器：x18 (预期正确值：888)
    # 提示：本例假设你的 DataMemory 开头有一些可用地址，这里用 0x40 演示                   【通过！】
    # =========================================================================
test_load_use:
    addi x21, x0, 887       # x21 = 888
    sw   x21, 0(gp)        # M[0x4000] = 888

    # 核心测试点：lw 读数，下一条指令立马要用这个数
    lw   x22, 0(gp)        # 从 0x4000 读出 887 存入 x22
    addi  x18, x22, 1      # 【必须触发 Stall】硬件产生一个空泡，然后 WB->EX 前传数据给 x18

    # =========================================================================
    # 测试结束：验证大满贯
    # =========================================================================
check_all_pass:
    addi x31, x0, 99        # 如果 CPU 能顺利走到这里且没死机，x31 写入 99

    # 优雅停机
    li x17, 10
    ecall
