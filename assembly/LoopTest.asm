.text
.global main
main:
    # =========================================================================
    # 1. 初始化参数 (DataMemory 从 0x40 开始)
    # =========================================================================
    addi x5, x0, 64         # x5 = mem_ptr = 0x40 (固定读写这个内存地址)
    
    addi x6, x0, 0          # x6 = 初始值 = 0
    sw   x6, 0(x5)          # M[0x40] = 0 (先把 0 写入内存作为起点)

    addi x12, x0, 0         # x12 = 循环计数器 (i = 0)
    addi x13, x0, 500       # x13 = 终点线 (严格累加到 500 次)

    # =========================================================================
    # 2. 核心极简循环 (lw 停顿 + sw 访存 + 分支控制)
    # =========================================================================
simple_loop:
    # --- 【核心轰炸点 1】: 读出内存中的当前值 ---
    lw   x6, 0(x5)          # x6 = M[0x40] (从内存加载最新值)

    # --- 【核心轰炸点 2】: Load-Use 冲突 (五级流水线在此处必 Stall 1 拍) ---
    # 因为上一条 lw x6 的数据在第 4 阶段(MEM)结束才从内存吐出来，
    # 而这一条 addi 立马就要在第 3 阶段(EX)使用 x6！硬件必须强制卡住 Stall 一拍！
    addi x6, x6, 1          # x6 = x6 + 1

    # --- 【核心轰炸点 3】: 将加 1 后的新值存回内存 ---
    sw   x6, 0(x5)          # M[0x40] = x6 (立刻存回内存)
                            # 这里的待存数据 x6 依赖上一条 addi，触发 EX->EX 前向传导

    # --- 循环计数与控制 ---
    addi x12, x12, 1        # i++ (循环计数器加 1)
    
    # 【控制冒险】：blt 跳转成功时冲刷 1 拍 (flush_if_id)
    blt  x12, x13, simple_loop

    # =========================================================================
    # 3. 测试结束验证与结果锁存
    # =========================================================================
    # 循环彻底结束后，最后一发 sw 已经把 500 砸进了内存。
    # 我们再次用 lw 从内存中把最终结果捞出来送给 x11，用于最终判决！
    lw   x11, 0(x5)         # 精准读取 M[0x40] 的最终结果到 x11
    
    li x0, 0
    
    add  x10, x12, x0        # x10 = 最终迭代次数 (验证是否跑完，应等于 500)
    
    addi x31, x0, 99        # 成功通关标志
    addi x17, x0, 10
    ecall